#!/usr/bin/env node
// Generates js/pricing-rates.js from assistant.pricing_rules (id
// 'web_ratecard_GLOBAL') in Supabase.
//
// WHY THIS IS A SCRIPT. js/pricing-rates.js already fixed half the problem: it
// made the seven pricing pages read ONE file instead of each hand-copying the
// rates, after six of them drifted onto a stale model that quoted US buyers about
// 23% under. But that file was itself hand-typed, and it was never derived from
// what a build actually costs. So the numbers a buyer sees still lived in a
// different place from the numbers the estimator prices with, and nothing made
// them agree.
//
// This closes it. The rate card lives in the database beside the cost catalog and
// the roll-up percentages, and this script writes the JS. To change a published
// price you change the row and regenerate; you do not edit the file.
//
// The seeded row is byte-for-byte the constants the file already carried, so the
// first generation changes nothing. Verify with scripts/check-pricing-parity.mjs,
// which executes every page's real engine and is the actual guard.
//
// Run: node scripts/gen-pricing-rates.mjs           (writes js/pricing-rates.js)
//      node scripts/gen-pricing-rates.mjs --check   (exits 1 if stale or invalid)
//
// Needs SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY. In --check mode without them
// the structural invariants still run against the committed file and only the
// drift comparison is skipped, exactly like gen-intake-catalog.mjs.

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname.replace(/\/$/, '');
const OUT = join(ROOT, 'js', 'pricing-rates.js');
const CHECK = process.argv.includes('--check');
const ROW_ID = 'web_ratecard_GLOBAL';

async function fetchRules() {
  const url = process.env.SUPABASE_URL, key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) return null;
  const res = await fetch(`${url.replace(/\/$/, '')}/rest/v1/pricing_rules?id=eq.${ROW_ID}&select=rules`,
    { headers: { apikey: key, Authorization: `Bearer ${key}`, 'Accept-Profile': 'assistant' } });
  if (!res.ok) throw new Error(`pricing_rules fetch failed: ${res.status} ${await res.text()}`);
  const rows = await res.json();
  if (!rows.length) throw new Error(`pricing_rules has no row '${ROW_ID}'`);
  return rows[0].rules;
}

const n = (v) => {
  if (typeof v !== 'number' || !Number.isFinite(v)) throw new Error(`not a finite number: ${JSON.stringify(v)}`);
  return String(v);
};
const tier = (t) => `{ v: ${n(t.v)}, f: ${n(t.f)} }`;

function render(r) {
  const country = (c) => ['watertight', 'builder', 'custom']
    .map((k) => `      ${k}: ${tier(r.country_rates[c][k])}`).join(',\n');
  // Fixed key order: jsonb does not preserve insertion order, and a file that
  // reshuffles itself on every regeneration produces noise diffs that hide real ones.
  const flat = (o, order) => order.filter((k) => k in o)
    .map((k) => `    ${k}: { cost: ${n(o[k])} }`).join(',\n');
  return `// js/pricing-rates.js
//
// GENERATED by scripts/gen-pricing-rates.mjs from assistant.pricing_rules
// ('${ROW_ID}'). DO NOT EDIT THIS FILE. Change the database row and
// regenerate; an edit here is overwritten and, worse, silently disagrees with
// what the estimator prices with.
//
// SINGLE SOURCE OF TRUTH for every pricing constant used by the 7
// EcoDomeHomes pricing calculators (root/en, de, es, fr, nl, pt, us/en).
// No pricing page may hardcode a rate, a fixed fee, an add-on/greenhouse cost,
// the EUR/USD rate, or the m2<->ft2 factor locally -- it must read
// window.EDH_PRICING instead.
//
// Before this file existed, each locale hand-copied these numbers into its own
// inline <script> and they drifted: six EUR-labelled pages kept a stale rate
// model with a wrong US figure -- {v:1010,f:81500} instead of the real
// {v:2100,f:0} -- quoting US buyers about 23% under (117 m2 builder:
// 231,617 USD stale vs 285,700 USD correct).
//
// scripts/check-pricing-parity.mjs EXECUTES each page's real inline pricing
// engine in a node:vm sandbox and fails the build the moment any page's rate
// constants drift from this file again.
//
// Loaded as a plain classic script (no bundler, no ES modules on this site):
// \`<script src="/js/pricing-rates.js"></script>\`, placed immediately before
// the page's inline pricing-engine <script> (NOT deferred).
(function () {
  'use strict';

  // Per-country, per-tier build rate. total = size_m2 * v + f (fixed fee).
  // A flat per-m2 rate with no fixed fee (the US model) is just f: 0.
  var COUNTRY_RATES = {
    portugal: {
${country('portugal')}
    },
    us: {
${country('us')}
    }
  };

  // English display names. Used as-is by the root (en) and us (en) pages. The 5
  // translated locale pages keep their own translated copy -- UI text, not
  // pricing data, so it stays page-local by design.
  var COUNTRY_NAMES = { portugal: 'Portugal', us: 'United States' };

  var EUR_TO_USD = ${n(r.eur_to_usd)};
  var M2_TO_FT2 = ${n(r.m2_to_ft2)};

  // Upper-floor add-on, EUR/m2 (or EUR-equivalent m2 for the US engine). The two
  // engine families have always used two different figures; both are kept here so
  // nothing computed changes and a future reconciliation has them in one place.
  var FLOOR_RATE = { portugal: ${n(r.floor_rate.portugal)}, us: ${n(r.floor_rate.us)} };

  var GREENHOUSE_META = {
${flat(r.greenhouse, ['none', 'integrated', 'standalone'])}
  };
  var ADDON_META = {
${flat(r.addons, ['solar', 'water', 'glazing', 'smart', 'ev'])}
  };

  window.EDH_PRICING = {
    COUNTRY_RATES: COUNTRY_RATES,
    COUNTRY_NAMES: COUNTRY_NAMES,
    EUR_TO_USD: EUR_TO_USD,
    M2_TO_FT2: M2_TO_FT2,
    FLOOR_RATE: FLOOR_RATE,
    GREENHOUSE_META: GREENHOUSE_META,
    ADDON_META: ADDON_META
  };
})();
`;
}

// Invariants that hold whether or not the database is reachable.
function validate(js) {
  const bad = [];
  for (const k of ['COUNTRY_RATES', 'EUR_TO_USD', 'M2_TO_FT2', 'FLOOR_RATE', 'GREENHOUSE_META', 'ADDON_META', 'window.EDH_PRICING'])
    if (!js.includes(k)) bad.push(`missing ${k}`);
  for (const c of ['portugal', 'us']) for (const t of ['watertight', 'builder', 'custom'])
    if (!new RegExp(`${t}:\\s*\\{\\s*v:\\s*\\d`).test(js)) bad.push(`${c}/${t} has no numeric rate`);
  if (/[\u2014\u2013]/.test(js)) bad.push('em or en dash present');
  if (/\bv:\s*0\b/.test(js)) bad.push('a per-m2 rate is zero, which would quote a build at its fixed fee alone');
  return bad;
}

const rules = await fetchRules();
const current = readFileSync(OUT, 'utf8');

if (CHECK) {
  const problems = validate(current);
  if (!rules) {
    if (problems.length) { problems.forEach((p) => console.error('  ' + p)); process.exit(1); }
    console.log('pricing-rates.js passes invariants. SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY not set, so drift against pricing_rules was not checked.');
    process.exit(0);
  }
  const fresh = render(rules);
  if (problems.length) { problems.forEach((p) => console.error('  ' + p)); process.exit(1); }
  if (fresh !== current) {
    console.error(`js/pricing-rates.js does not match assistant.pricing_rules ('${ROW_ID}'). Run: node scripts/gen-pricing-rates.mjs`);
    process.exit(1);
  }
  console.log('pricing-rates.js is up to date with assistant.pricing_rules.');
  process.exit(0);
}

if (!rules) { console.error('SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY are required to generate.'); process.exit(1); }
const out = render(rules);
const problems = validate(out);
if (problems.length) { console.error('refusing to write:'); problems.forEach((p) => console.error('  ' + p)); process.exit(1); }
writeFileSync(OUT, out);
console.log(`Wrote js/pricing-rates.js from assistant.pricing_rules ('${ROW_ID}').`);
